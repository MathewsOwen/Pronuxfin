import type { DeskMarketId } from "@/lib/market/world-markets";
import type { SectorId } from "@/lib/market/sector-universe";

type WorldSectorMap = Record<SectorId, readonly string[]>;

function map(
  commodities: string,
  technology: string,
  oil_gas: string,
  defense_aerospace: string,
  financials: string,
  healthcare: string,
  consumer: string,
  utilities: string,
  industrials: string,
): WorldSectorMap {
  const w = (s: string) => s.trim().split(/\s+/).filter(Boolean);
  return {
    commodities: w(commodities),
    technology: w(technology),
    oil_gas: w(oil_gas),
    defense_aerospace: w(defense_aerospace),
    financials: w(financials),
    healthcare: w(healthcare),
    consumer: w(consumer),
    utilities: w(utilities),
    industrials: w(industrials),
  };
}

